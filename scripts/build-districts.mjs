import fs from "node:fs";
import path from "node:path";

const adm1Path = path.resolve("data/raw/zmb-adm1.geojson");
const adm2Path = path.resolve("data/raw/zmb-adm2.geojson");
const out = path.resolve("src/data/districts.ts");

if (!fs.existsSync(adm1Path) || !fs.existsSync(adm2Path)) {
  console.error("Missing data/raw/zmb-adm1.geojson or data/raw/zmb-adm2.geojson");
  process.exit(1);
}

const adm1 = JSON.parse(fs.readFileSync(adm1Path, "utf8"));
const adm2 = JSON.parse(fs.readFileSync(adm2Path, "utf8"));

const provinceId = {
  Eastern: "eastern",
  Muchinga: "muchinga",
  "North-Western": "north-western",
  Luapula: "luapula",
  Central: "central",
  Southern: "southern",
  Lusaka: "lusaka",
  Copperbelt: "copperbelt",
  Northern: "northern",
  Western: "western",
};

function pointInRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    const crosses = yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi + 0) + xi;
    if (crosses) inside = !inside;
  }
  return inside;
}

function contains(geometry, lon, lat) {
  const polygons = geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  return polygons.some((polygon) => {
    if (!pointInRing(lon, lat, polygon[0])) return false;
    return !polygon.slice(1).some((hole) => pointInRing(lon, lat, hole));
  });
}

function exterior(geometry) {
  const polygons = geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  return polygons.flatMap((polygon) => polygon[0]);
}

function centroid(ring) {
  let area = 0;
  let cx = 0;
  let cy = 0;
  for (let i = 0; i < ring.length - 1; i += 1) {
    const [x1, y1] = ring[i];
    const [x2, y2] = ring[i + 1];
    const cross = x1 * y2 - x2 * y1;
    area += cross;
    cx += (x1 + x2) * cross;
    cy += (y1 + y2) * cross;
  }
  area *= 0.5;
  if (Math.abs(area) < 1e-12) {
    const n = Math.max(ring.length - 1, 1);
    const sum = ring.slice(0, -1).reduce((acc, point) => [acc[0] + point[0], acc[1] + point[1]], [0, 0]);
    return [sum[0] / n, sum[1] / n];
  }
  return [cx / (6 * area), cy / (6 * area)];
}

function slug(name) {
  return name
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

const provinces = adm1.features.map((feature) => {
  const name = feature.properties.shapeName;
  const id = provinceId[name];
  if (!id) throw new Error(`ADM1 name has no province id: ${name}`);
  return { id, name, geometry: feature.geometry };
});

const baseNote =
  "District polygon from geoBoundaries ADM2, CC BY 4.0, boundary year 2020. geoBoundaries names the source as GRID3 and the Office of the Surveyor General. The file used here is their simplified geometry. The province is the ADM1 polygon, same release, that contains the most of this district's vertices. That join is not a legal determination, and the district is not drawn on the plate.";

const used = new Set();
const districts = adm2.features.map((feature) => {
  const name = feature.properties.shapeName;
  const id = `district-${slug(name)}`;
  if (!id || id === "district-" || used.has(id)) throw new Error(`Bad or duplicate district id for ${name}`);
  used.add(id);
  const points = exterior(feature.geometry);
  const scores = new Map(provinces.map((province) => [province.id, 0]));
  for (const [lon, lat] of points) {
    for (const province of provinces) {
      if (contains(province.geometry, lon, lat)) scores.set(province.id, scores.get(province.id) + 1);
    }
  }
  const ranked = [...scores.entries()].sort((left, right) => right[1] - left[1]);
  const [parentId, hits] = ranked[0];
  const share = points.length ? hits / points.length : 0;
  const assigned = share >= 0.75 ? parentId : undefined;
  const [longitude, latitude] = centroid(points);
  const note = assigned
    ? `${baseNote} shapeID ${feature.properties.shapeID}.`
    : `${baseNote} The simplified polygon did not fall mostly inside one province, so no province is attached. shapeID ${feature.properties.shapeID}.`;
  return {
    id,
    name,
    kind: "district",
    parentId: assigned,
    latitude: Number(latitude.toFixed(5)),
    longitude: Number(longitude.toFixed(5)),
    note,
    share: Number(share.toFixed(3)),
    candidateId: parentId,
  };
});

districts.sort((left, right) => left.name.localeCompare(right.name));
const unassigned = districts.filter((district) => !district.parentId);
const body = `/* Generated by scripts/build-districts.mjs. Do not edit by hand.
   geoBoundaries ZMB ADM2 simplified, CC BY 4.0, boundary year 2020, release commit 9469f09.
   Province join uses geoBoundaries ZMB ADM1 from the same release. ${unassigned.length} districts were left without a province.
*/
import type { PlaceSeed } from "./places";

export const districts: PlaceSeed[] = ${JSON.stringify(
  districts.map(({ share: _share, candidateId: _candidate, ...district }) => district),
  null,
  2,
)};
`;

fs.writeFileSync(out, body);
const weakest = [...districts].sort((left, right) => left.share - right.share);
for (const district of weakest.filter((item) => item.share < 0.9)) {
  console.log(`${district.share}\t${district.parentId ?? `unassigned:${district.candidateId}`}\t${district.name}`);
}
console.log(`wrote ${districts.length} districts, unassigned ${unassigned.length}`);
