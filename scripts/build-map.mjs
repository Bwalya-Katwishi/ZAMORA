import fs from "node:fs";
import path from "node:path";

const source = path.resolve("data/raw/zmb-adm1.geojson");
const out = path.resolve("src/data/map.ts");
const geo = JSON.parse(fs.readFileSync(source, "utf8"));

function dist(p, a, b) {
  const [x, y] = p;
  const [x1, y1] = a;
  const [x2, y2] = b;
  const dx = x2 - x1;
  const dy = y2 - y1;
  const len = Math.hypot(dx, dy) || 1;
  return Math.abs(dy * x - dx * y + x2 * y1 - y2 * x1) / len;
}

function simplify(points, eps) {
  if (points.length < 3) return points;
  let max = 0;
  let idx = 0;
  const a = points[0];
  const b = points[points.length - 1];
  for (let i = 1; i < points.length - 1; i += 1) {
    const d = dist(points[i], a, b);
    if (d > max) {
      max = d;
      idx = i;
    }
  }
  if (max > eps) {
    const left = simplify(points.slice(0, idx + 1), eps);
    const right = simplify(points.slice(idx), eps);
    return left.slice(0, -1).concat(right);
  }
  return [a, b];
}

function simplifyRing(ring, eps) {
  const closed =
    ring.length > 2 &&
    ring[0][0] === ring[ring.length - 1][0] &&
    ring[0][1] === ring[ring.length - 1][1];
  const open = closed ? ring.slice(0, -1) : ring.slice();
  const simplified = simplify(open, eps);
  if (simplified.length === 0) return ring;
  simplified.push(simplified[0]);
  return simplified;
}

function ringArea(ring) {
  let sum = 0;
  for (let i = 0; i < ring.length - 1; i += 1) {
    sum += ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1];
  }
  return Math.abs(sum / 2);
}

const polygons = [];
let minLon = Infinity;
let maxLon = -Infinity;
let minLat = Infinity;
let maxLat = -Infinity;

for (const feature of geo.features) {
  const name = feature.properties.shapeName;
  const geometry = feature.geometry;
  const polys = geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  const rings = [];
  for (const poly of polys) {
    const simplified = poly.map((ring) => simplifyRing(ring, 0.03));
    rings.push(simplified);
    for (const ring of simplified) {
      for (const [lon, lat] of ring) {
        minLon = Math.min(minLon, lon);
        maxLon = Math.max(maxLon, lon);
        minLat = Math.min(minLat, lat);
        maxLat = Math.max(maxLat, lat);
      }
    }
  }
  polygons.push({ name, rings });
}

const pad = 36;
const width = 760;
const height = 820;
const midLat = (minLat + maxLat) / 2;
const cos = Math.cos((midLat * Math.PI) / 180);
const spanX = (maxLon - minLon) * cos;
const spanY = maxLat - minLat;
const scale = Math.min((width - pad * 2) / spanX, (height - pad * 2) / spanY);

function project(lon, lat) {
  const x = pad + (lon - minLon) * cos * scale;
  const y = pad + (maxLat - lat) * scale;
  return [Number(x.toFixed(2)), Number(y.toFixed(2))];
}

function pathFor(rings) {
  return rings
    .map((poly) =>
      poly
        .map((ring) => {
          const pts = ring.map(([lon, lat]) => project(lon, lat));
          return pts.map((p, i) => `${i === 0 ? "M" : "L"}${p[0]} ${p[1]}`).join(" ") + " Z";
        })
        .join(" "),
    )
    .join(" ");
}

function centroid(rings) {
  let best = rings[0][0];
  let bestArea = -1;
  for (const poly of rings) {
    const area = ringArea(poly[0]);
    if (area > bestArea) {
      bestArea = area;
      best = poly[0];
    }
  }
  let sx = 0;
  let sy = 0;
  const n = Math.max(best.length - 1, 1);
  for (let i = 0; i < best.length - 1; i += 1) {
    const [x, y] = project(best[i][0], best[i][1]);
    sx += x;
    sy += y;
  }
  return [Number((sx / n).toFixed(2)), Number((sy / n).toFixed(2))];
}

const slug = {
  Eastern: "eastern",
  Muchinga: "muchinga",
  "North-Western": "north-western",
  Luapula: "luapula",
  Central: "central",
  Southern: "southern",
  Lusaka: "lusaka",
  Copperbelt: "copperbelt",
  Northern: "northern",
  Western: "western",
};

const provinces = polygons.map((polygon) => ({
  id: slug[polygon.name],
  name: polygon.name,
  d: pathFor(polygon.rings),
  label: centroid(polygon.rings),
}));

const body = `/* Generated by scripts/build-map.mjs. Do not edit by hand.
   Province geometry: geoBoundaries ADM1, CC BY 4.0, boundary year 2020.
   Simplified for the ZAMORA plate. This is a research scaffold, not a legal boundary survey.
*/
export const mapView = {
  width: ${width},
  height: ${height},
  minLon: ${minLon},
  maxLon: ${maxLon},
  minLat: ${minLat},
  maxLat: ${maxLat},
  pad: ${pad},
  scale: ${scale},
  cos: ${cos},
} as const;

export function project(lon: number, lat: number): [number, number] {
  const x = ${pad} + (lon - ${minLon}) * ${cos} * ${scale};
  const y = ${pad} + (${maxLat} - lat) * ${scale};
  return [x, y];
}

export const provinces = ${JSON.stringify(provinces, null, 2)} as const;
`;

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, body);
console.log(`wrote ${out} provinces ${provinces.length}`);
